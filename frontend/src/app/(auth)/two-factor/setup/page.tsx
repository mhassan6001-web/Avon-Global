"use client";

import { useRouter } from "next/navigation";
import { useEffect, useState } from "react";

import { Button, FormError, Spinner, TextField } from "@/components/ui";
import { ApiError, send } from "@/lib/api/client";

import styles from "../../auth.module.css";

interface SetupOut {
  secret: string;
  otpauth_uri: string;
  qr_svg: string;
}

export default function TwoFactorSetupPage() {
  const router = useRouter();
  const [setup, setSetup] = useState<SetupOut | null>(null);
  const [code, setCode] = useState("");
  const [codes, setCodes] = useState<string[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    send<SetupOut>("POST", "/auth/2fa/setup")
      .then(({ data }) => setSetup(data))
      .catch((e: unknown) => {
        if (e instanceof ApiError && e.status === 401) router.replace("/sign-in");
        else setError(e instanceof ApiError ? e.message : "Could not start setup.");
      });
  }, [router]);

  async function enable() {
    setBusy(true);
    setError(null);
    try {
      const { data } = await send<{ recovery_codes: string[] }>("POST", "/auth/2fa/enable", {
        body: { code },
      });
      setCodes(data.recovery_codes);
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "That code did not work.");
    } finally {
      setBusy(false);
    }
  }

  if (codes) {
    return (
      <div>
        <h1 className={styles.title}>Save your recovery codes</h1>
        <p className={styles.lead}>
          Each code works once if you lose your phone. Store them somewhere safe. They will not be
          shown again.
        </p>
        <div className={styles.codes} data-testid="recovery-codes">
          {codes.map((c) => (
            <span key={c}>{c}</span>
          ))}
        </div>
        <div className={styles.actions}>
          <Button variant="primary" onClick={() => router.replace("/")}>
            I have saved them, continue
          </Button>
        </div>
      </div>
    );
  }

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        void enable();
      }}
    >
      <h1 className={styles.title}>Set up two-factor sign-in</h1>
      <p className={styles.lead}>
        Your role requires an authenticator app (for example Google Authenticator, Microsoft
        Authenticator or 1Password). Scan the code, then enter the 6 digits it shows.
      </p>
      {setup ? (
        <>
          {/* SVG generated by our own API from the provisioning URI (no user input). */}
          <div className={styles.qr} dangerouslySetInnerHTML={{ __html: setup.qr_svg }} />
          <p className={styles.lead} style={{ marginBottom: 4 }}>
            Can&apos;t scan? Enter this key manually:
          </p>
          <p className={styles.secret} data-testid="totp-secret">
            {setup.secret}
          </p>
        </>
      ) : (
        !error && <Spinner label="Preparing" />
      )}
      <TextField
        label="Code from your app"
        inputMode="numeric"
        autoComplete="one-time-code"
        value={code}
        onChange={(e) => setCode(e.target.value)}
        required
      />
      <FormError message={error} />
      <div className={styles.actions}>
        <Button variant="primary" type="submit" loading={busy} disabled={!setup}>
          Turn on
        </Button>
      </div>
    </form>
  );
}

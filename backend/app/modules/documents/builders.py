TZ = ZoneInfo("Africa/Blantyre")
REG_LABEL = {
    "not_confirmed": "Registration not yet confirmed",
    "pending": "Registration pending",
}


def money(value: Decimal | None) -> str:
    return f"{(value or Decimal(0)):,.2f}"


def qty(value: Decimal) -> str:
    text = f"{value:,.3f}".rstrip("0").rstrip(".")
    return text or "0"


def day(value: date | datetime | None) -> str:
    if value is None:
        return "—"
    if isinstance(value, datetime):
        value = value.astimezone(TZ)
    return f"{value:%d %b %Y}"


def _org(db: Session) -> OrganisationProfile | None:
    return db.execute(select(OrganisationProfile).limit(1)).scalar_one_or_none()


def issuer_lines(db: Session) -> list[str]:
    """Company block for documents. Address, phone, email, TPIN and VAT number
    appear only when the Director has approved each of them for print."""
    org = _org(db)
    if org is None:
        return ["Organisation profile not set up"]
    lines = [org.legal_name or f"{org.trading_name} (legal name not yet confirmed)"]
    if org.print_address and org.address_line1:
        lines.append(", ".join(x for x in (org.address_line1, org.address_line2) if x))
    place = ", ".join(x for x in (org.headquarters_city, org.headquarters_country_code) if x)
    if place:
        lines.append(place)
    contact = [
        f"Tel {org.phone}" if org.print_phone and org.phone else None,
        org.email if org.print_email and org.email else None,
    ]
    if any(contact):
        lines.append(" · ".join(x for x in contact if x))
    if org.registration_status == "registered" and org.registration_number:
        lines.append(f"Registration no. {org.registration_number}")
    else:
        lines.append(REG_LABEL.get(org.registration_status, "Registration not confirmed"))
    tax = [
        f"TPIN {org.tpin}" if org.print_tpin and org.tpin else None,
        f"VAT reg. no. {org.vat_number}" if org.print_vat and org.vat_number else None,
    ]
    if any(tax):
        lines.append(" · ".join(x for x in tax if x))
    return lines


def vat_printable(db: Session) -> bool:
    org = _org(db)
    return bool(org and org.print_vat and org.vat_number)


def _name(db: Session, user_id: uuid.UUID | None) -> str | None:
    user = db.get(User, user_id) if user_id else None
    return user.display_name if user else None


def footer(generated_by: str, now: datetime) -> list[str]:
    return [
        f"Generated by AVEN GLOBAL for {generated_by} on {now.astimezone(TZ):%d %b %Y %H:%M} "
        "(Africa/Blantyre) from the system record.",
        "No signature or stamp is applied by the system.",
    ]


def _demo(is_demo: bool) -> list[str]:
    return ["DEVELOPMENT DEMO DATA - NOT A REAL DOCUMENT"] if is_demo else []


def invoice(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    inv = db.get(Invoice, record_id)
    if inv is None:
        raise NotFoundError("Invoice not found.")
    customer = db.get(Customer, inv.customer_id)
    lines = list(
        db.execute(
            select(InvoiceLine)
            .where(InvoiceLine.invoice_id == inv.id)
            .order_by(InvoiceLine.line_no)
        ).scalars()
    )
    codes = {
        t.id: t
        for t in db.execute(
            select(TaxCode).where(
                TaxCode.id.in_({ln.tax_code_id for ln in lines if ln.tax_code_id})
            )
        ).scalars()
    }
    banners = _demo(bool(customer and customer.is_demo))
    if inv.status == "draft":
        banners.insert(0, "DRAFT - NOT ISSUED")
    balance = inv.total - inv.amount_paid - inv.amount_credited
    meta = [
        ("Issue date", day(inv.issue_date)),
        ("Due date", day(inv.due_date)),
        ("Currency", inv.currency),
        ("Status", inv.status.replace("_", " ")),
    ]
    if inv.issued_at:
        meta.append(
            ("Issued in system by", f"{_name(db, inv.issued_by) or '—'}, {day(inv.issued_at)}")
        )
    rows = []
    for ln in lines:
        code = codes.get(ln.tax_code_id) if ln.tax_code_id else None
        rows.append(
            [
                ln.description,
                qty(ln.quantity),
                money(ln.unit_price),
                f"{code.code} {code.rate_pct.normalize():f}%" if code else "—",
                money(ln.tax),
                money(ln.net + ln.tax),
            ]
        )
    return Document(
        # "Tax invoice" only once a VAT number is confirmed and approved for print.
        kind="Tax invoice" if inv.tax_total and vat_printable(db) else "Invoice",
        number=inv.number or "DRAFT",
        issuer=issuer_lines(db),
        recipient_title="Bill to",
        recipient=[
            x
            for x in (
                customer.name if customer else "—",
                customer and customer.city,
                customer and customer.email,
            )
            if x
        ],
        meta=meta,
        columns=[
            Column("Description", 5),
            Column("Qty", 1.1, "right"),
            Column("Unit price", 1.6, "right"),
            Column("Tax code", 1.4, "right"),
            Column("Tax", 1.4, "right"),
            Column("Amount", 1.8, "right"),
        ],
        rows=rows,
        totals=[
            ("Subtotal", money(inv.subtotal)),
            ("Tax", money(inv.tax_total)),
            ("Total", f"{inv.currency} {money(inv.total)}"),
            ("Paid", money(inv.amount_paid)),
            ("Credited", money(inv.amount_credited)),
            ("Balance due", f"{inv.currency} {money(balance)}"),
        ],
        notes=[inv.notes] if inv.notes else [],
        footer=footer(by, now),
        banners=banners,
    )


def receipt(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    rc = db.get(Receipt, record_id)
    if rc is None:
        raise NotFoundError("Receipt not found.")
    customer = db.get(Customer, rc.customer_id)
    return Document(
        kind="Receipt",
        number=rc.number,
        issuer=issuer_lines(db),
        recipient_title="Received from",
        recipient=[
            x for x in (customer.name if customer else "—", customer and customer.city) if x
        ],
        meta=[
            ("Date", day(rc.receipt_date)),
            ("Method", rc.method.replace("_", " ")),
            ("Reference", rc.reference or "—"),
            ("Recorded by", _name(db, rc.created_by) or "—"),
        ],
        columns=[Column("Description", 6), Column("Amount", 2, "right")],
        rows=[["Payment received", f"{rc.currency} {money(rc.amount)}"]],
        totals=[("Amount received", f"{rc.currency} {money(rc.amount)}")],
        footer=footer(by, now),
        banners=_demo(bool(customer and customer.is_demo)),
    )


def purchase_order(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    po = db.get(PurchaseOrder, record_id)
    if po is None:
        raise NotFoundError("Purchase order not found.")
    supplier = db.get(Supplier, po.supplier_id)
    lines = list(
        db.execute(
            select(PurchaseOrderLine)
            .where(PurchaseOrderLine.order_id == po.id)
            .order_by(PurchaseOrderLine.line_no)
        ).scalars()
    )
    banners = ["CANCELLED"] if po.status == "cancelled" else []
    return Document(
        kind="Purchase order",
        number=po.reference,
        issuer=issuer_lines(db),
        recipient_title="Supplier",
        recipient=[
            x
            for x in (
                supplier.name if supplier else "—",
                supplier and supplier.contact_name,
                supplier and supplier.city,
                supplier and supplier.email,
            )
            if x
        ],
        meta=[
            ("Currency", po.currency),
            ("Expected delivery", day(po.expected_delivery)),
            ("Status", po.status.replace("_", " ")),
            ("Issued in system by", _name(db, po.issued_by) or "—"),
        ],
        columns=[
            Column("Description", 5),
            Column("Qty", 1.2, "right"),
            Column("Unit", 1, "left"),
            Column("Unit price", 1.6, "right"),
            Column("Amount", 1.8, "right"),
        ],
        rows=[
            [
                ln.description,
                qty(ln.quantity),
                ln.unit or "",
                money(ln.unit_price),
                money(ln.line_total),
            ]
            for ln in lines
        ],
        totals=[("Total", f"{po.currency} {money(po.total_amount)}")],
        notes=[f"Deliver to: {po.delivery_address}"] if po.delivery_address else [],
        footer=footer(by, now),
        banners=banners,
    )


def delivery_note(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    dn = db.get(DeliveryNote, record_id)
    if dn is None:
        raise NotFoundError("Delivery note not found.")
    customer = db.get(Customer, dn.customer_id)
    warehouse = db.get(Warehouse, dn.warehouse_id)
    lines = list(
        db.execute(
            select(DeliveryNoteLine, Product)
            .join(Product, Product.id == DeliveryNoteLine.product_id)
            .where(DeliveryNoteLine.delivery_note_id == dn.id)
            .order_by(DeliveryNoteLine.line_no)
        ).tuples()
    )
    meta = [
        ("Scheduled", day(dn.scheduled_for)),
        ("From warehouse", warehouse.code if warehouse else "—"),
        ("Status", dn.status),
    ]
    if dn.delivered_at:
        meta.append(
            ("Delivered", f"{day(dn.delivered_at)}, received by {dn.received_by_name or '—'}")
        )
    banners = _demo(bool(customer and customer.is_demo))
    if dn.status == "draft":
        banners.insert(0, "DRAFT - NOT DISPATCHED")
    return Document(
        kind="Delivery note",
        number=dn.number,
        issuer=issuer_lines(db),
        recipient_title="Deliver to",
        recipient=[x for x in (customer.name if customer else "—", dn.delivery_address) if x],
        meta=meta,
        columns=[
            Column("SKU", 1.6),
            Column("Item", 5),
            Column("Qty", 1.2, "right"),
            Column("Unit", 1),
        ],
        rows=[[p.sku, p.name, qty(ln.quantity), p.unit] for ln, p in lines],
        notes=["Received in good order (name, date):"] if dn.status != "delivered" else [],
        footer=footer(by, now),
        banners=banners,
    )


def quotation(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    q = db.get(Quotation, record_id)
    if q is None:
        raise NotFoundError("Quotation not found.")
    customer = db.get(Customer, q.customer_id)
    lines = list(
        db.execute(
            select(QuotationLine)
            .where(QuotationLine.quotation_id == q.id)
            .order_by(QuotationLine.line_no)
        ).scalars()
    )
    ids = {ln.tax_code_id for ln in lines if ln.tax_code_id}
    codes = {t.id: t for t in db.execute(select(TaxCode).where(TaxCode.id.in_(ids))).scalars()}
    banners = _demo(bool(customer and customer.is_demo))
    if q.status in ("draft", "awaiting_approval"):
        banners.insert(0, "DRAFT - NOT ISSUED")
    elif q.status in ("cancelled", "declined"):
        banners.insert(0, q.status.upper())
    elif q.status == "issued" and q.valid_until < now.astimezone(TZ).date():
        banners.insert(0, "EXPIRED")
    meta = [
        ("Date", day(q.quote_date)),
        ("Valid until", day(q.valid_until)),
        ("Currency", q.currency),
        ("Prepared by", _name(db, q.created_by) or "—"),
    ]
    rows = []
    for ln in lines:
        code = codes.get(ln.tax_code_id) if ln.tax_code_id else None
        rows.append(
            [
                ln.description,
                qty(ln.quantity),
                ln.unit,
                money(ln.unit_price),
                f"{code.code} {code.rate_pct.normalize():f}%" if code else "—",
                money(ln.net + ln.tax),
            ]
        )
    notes = [f"Subject: {q.title}"]
    if q.terms:
        notes.append(f"Terms: {q.terms}")
    if q.notes:
        notes.append(q.notes)
    return Document(
        kind="Quotation",
        number=q.number or "DRAFT",
        issuer=issuer_lines(db),
        recipient_title="Quotation for",
        recipient=[
            x
            for x in (
                customer.name if customer else "—",
                customer and customer.city,
                customer and customer.email,
            )
            if x
        ],
        meta=meta,
        columns=[
            Column("Description", 5),
            Column("Qty", 1.1, "right"),
            Column("Unit", 1),
            Column("Unit price", 1.6, "right"),
            Column("Tax code", 1.4, "right"),
            Column("Amount", 1.8, "right"),
        ],
        rows=rows,
        totals=[
            ("Subtotal", money(q.subtotal)),
            ("Tax", money(q.tax_total)),
            ("Total", f"{q.currency} {money(q.total)}"),
        ],
        notes=notes,
        footer=footer(by, now),
        banners=banners,
    )


def rfq(db: Session, record_id: uuid.UUID, by: str, now: datetime) -> Document:
    """Request for quotation to send to suppliers: the items needed, no prices."""
    pr = db.get(PurchaseRequest, record_id)
    if pr is None:
        raise NotFoundError("Purchase request not found.")
    lines = list(
        db.execute(
            select(PurchaseRequestLine)
            .where(PurchaseRequestLine.request_id == pr.id)
            .order_by(PurchaseRequestLine.line_no)
        ).scalars()
    )
    return Document(
        kind="Request for quotation",
        number=f"RFQ-{pr.reference}",
        issuer=issuer_lines(db),
        recipient_title="To",
        recipient=["Supplier", "(name and address to be completed)"],
        meta=[
            ("Our reference", pr.reference),
            ("Subject", pr.title),
            ("Required by", day(pr.needed_by)),
            ("Quote in", pr.currency),
            ("Prepared by", _name(db, pr.requested_by) or "—"),
        ],
        columns=[
            Column("No.", 0.6),
            Column("Item", 5.5),
            Column("Quantity", 1.4, "right"),
            Column("Unit", 1.2),
            Column("Your unit price", 2, "right"),
        ],
        rows=[[str(ln.line_no), ln.description, qty(ln.quantity), ln.unit, ""] for ln in lines],
        notes=[
            "Please quote your unit price for each item, your delivery time and how long "
            "your quotation stays valid.",
            "This is a request for prices only. It is not an order.",
        ],
        footer=footer(by, now),
        banners=[],
    )


def statement(
    db: Session, customer_id: uuid.UUID, date_from: date, date_to: date, by: str, now: datetime
) -> tuple[Document, Sheet]:
    """Customer account statement as a document and as a worksheet."""
    from app.modules.finance import reports

    st = reports.statement(db, customer_id, date_from, date_to)
    customer = db.get(Customer, customer_id)
    label = {"invoice": "Invoice", "receipt": "Receipt", "credit_note": "Credit note"}
    rows = [
        [day(r.entry_date), f"{label[r.kind]} {r.number}", r.description, r.currency,
         money(r.debit) if r.debit else "", money(r.credit) if r.credit else "", money(r.balance)]
        for r in st.rows
    ]  # fmt: skip
    totals: list[tuple[str, str]] = []
    for t in st.totals:
        totals.append((f"Opening balance {t.currency}", money(t.opening)))
        totals.append((f"Balance due {t.currency}", f"{t.currency} {money(t.closing)}"))
    number = f"STMT-{customer.reference if customer else ''}-{date_to:%Y%m%d}"
    doc = Document(
        kind="Statement of account",
        number=number,
        issuer=issuer_lines(db),
        recipient_title="Account of",
        recipient=[
            x
            for x in (st.customer_name, customer and customer.city, customer and customer.email)
            if x
        ],
        meta=[("Period", f"{day(date_from)} to {day(date_to)}"), ("Statement date", day(now))],
        columns=[
            Column("Date", 1.5),
            Column("Document", 2.6),
            Column("Details", 3),
            Column("Cur", 0.8),
            Column("Charges", 1.7, "right"),
            Column("Payments", 1.7, "right"),
            Column("Balance", 1.8, "right"),
        ],
        rows=rows or [["", "No transactions in this period", "", "", "", "", ""]],
        totals=totals,
        notes=["Balances are shown separately for each currency and are not converted."],
        footer=footer(by, now),
        banners=_demo(bool(customer and customer.is_demo)),
    )
    sheet = Sheet(
        title="Statement of account",
        subtitle=_subtitle(db, f"{st.customer_name}: {day(date_from)} to {day(date_to)}", by, now),
        headers=["Date", "Type", "Number", "Details", "Currency", "Charges", "Payments", "Balance"],
        rows=[
            [
                r.entry_date.isoformat(),
                label[r.kind],
                r.number,
                r.description,
                r.currency,
                float(r.debit),
                float(r.credit),
                float(r.balance),
            ]
            for r in st.rows
        ],
        numeric={5, 6, 7},
    )
    return doc, sheet



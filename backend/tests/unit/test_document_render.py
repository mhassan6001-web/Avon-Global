"""Stage 13: the dependency-free PDF, Word and Excel writers."""

from __future__ import annotations

import io
import re
import zipfile
import zlib
from xml.etree import ElementTree

from app.modules.documents.model import Column, Document, Sheet
from app.modules.documents.render import docx, pdf, xlsx


def _doc(rows: int = 3) -> Document:
    return Document(
        kind="Tax invoice",
        number="INV-2026-00001",
        issuer=["AVEN GLOBAL (legal name not yet confirmed)", "Lilongwe, MW"],
        recipient_title="Bill to",
        recipient=["TEST Customer (Pty) Ltd", "Blantyre, MW"],
        meta=[("Issue date", "12 Nov 2026"), ("Currency", "MWK")],
        columns=[Column("Description", 5), Column("Qty", 1, "right"), Column("Amount", 2, "right")],
        rows=[
            [f"Item {i} with (brackets) and \\ slash — dash", "1", "1,000.00"] for i in range(rows)
        ],
        totals=[("Subtotal", "3,000.00"), ("Total", "MWK 3,000.00")],
        notes=["Tax rates are configured by Finance."],
        footer=["Generated by AVEN GLOBAL. No signature is applied."],
        banners=["DRAFT - NOT ISSUED"],
    )


def _pdf_text(data: bytes) -> bytes:
    out = b""
    for m in re.finditer(rb"stream\n(.*?)\nendstream", data, re.DOTALL):
        out += zlib.decompress(m.group(1))
    return out


def test_pdf_is_well_formed_and_escapes_text() -> None:
    data = pdf.render(_doc())
    assert data.startswith(b"%PDF-1.4") and data.rstrip().endswith(b"%%EOF")
    # The xref offsets point at real objects.
    xref = int(re.search(rb"startxref\n(\d+)", data).group(1))  # type: ignore[union-attr]
    assert data[xref : xref + 4] == b"xref"
    for off in re.findall(rb"(\d{10}) 00000 n", data):
        assert re.match(rb"\d+ 0 obj", data[int(off) :])
    text = _pdf_text(data)
    assert b"INV-2026-00001" in text and b"\\(brackets\\)" in text and b"\\\\ slash" in text
    assert b"DRAFT - NOT ISSUED" in text


def test_pdf_paginates_long_tables() -> None:
    data = pdf.render(_doc(rows=120))
    assert int(re.search(rb"/Count (\d+)", data).group(1)) >= 3  # type: ignore[union-attr]
    assert b"Page 3" in _pdf_text(data)


def test_text_width_uses_font_metrics() -> None:
    assert pdf.text_width("iiii", 10) < pdf.text_width("MMMM", 10)
    assert pdf.text_width("1,000.00", 10, "F2") > 0


def test_docx_is_a_valid_package() -> None:
    data = docx.render(_doc(), "2026-11-12T10:00:00Z")
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        assert {"[Content_Types].xml", "_rels/.rels", "word/document.xml"} <= set(z.namelist())
        root = ElementTree.fromstring(z.read("word/document.xml"))
    text = "".join(
        t.text or ""
        for t in root.iter("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}t")
    )
    assert "INV-2026-00001" in text and "TEST Customer (Pty) Ltd" in text


def test_xlsx_numbers_and_formula_injection() -> None:
    sheet = Sheet(
        title="Trial balance",
        subtitle=["As of 12 Nov 2026"],
        headers=["Account", "Debit"],
        rows=[['=HYPERLINK("x")', 10.5], ["Bank", None]],
        numeric={1},
    )
    data = xlsx.render(sheet)
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        ws = z.read("xl/worksheets/sheet1.xml").decode()
        ElementTree.fromstring(ws)
        ElementTree.fromstring(z.read("xl/workbook.xml"))
        ElementTree.fromstring(z.read("xl/styles.xml"))
    assert "<v>10.5</v>" in ws
    assert "'=HYPERLINK" in ws and "<f>" not in ws
